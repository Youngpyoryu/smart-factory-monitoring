
import streamlit as st

# --------------------------------------------------
# 1. 웹 프로그램 기본 설정
# --------------------------------------------------

st.set_page_config(
    page_title="스마트공장 모니터링",
    page_icon="🏭",
    layout="wide"
)

# --------------------------------------------------
# 2. 프로그램 제목 및 설명
# --------------------------------------------------

st.title("스마트공장 생산 모니터링 시스템")

st.write("공장의 생산량과 설비 상태를 확인하는 프로그램입니다.")

st.info("현재 표시되는 데이터는 교육용 가상 데이터입니다.")

# --------------------------------------------------
# 3. 사이드바 메뉴
# --------------------------------------------------

menu = st.sidebar.radio(
    "메뉴 선택",
    [
        "생산 현황",
        "품질 관리",
        "설비 모니터링",
        "데이터 관리"
    ]
)

# --------------------------------------------------
# 4. 생산 현황 메뉴
# --------------------------------------------------

if menu == "생산 현황":

    st.header("생산 현황")

    st.write("공장의 주요 생산지표를 확인합니다.")

    # 화면을 네 개의 열로 나누기
    col1, col2, col3, col4 = st.columns(4)

    # 첫 번째 열: 총생산량
    with col1:
        st.metric("총생산량", "1,000개")

    # 두 번째 열: 정상 제품
    with col2:
        st.metric("정상 제품", "950개")

    # 세 번째 열: 불량 제품
    with col3:
        st.metric("불량 제품", "50개")

    # 네 번째 열: 불량률
    with col4:
        st.metric("불량률", "5.0%")

    # 구분선 표시
    st.divider()

    # 평균 공정 온도 표시
    st.metric("평균 공정 온도", "38℃")

    # 다음 수업 안내
    st.write("다음 수업에서 실제 CSV 데이터를 연결합니다.")

# --------------------------------------------------
# 5. 품질 관리 메뉴
# --------------------------------------------------

elif menu == "품질 관리":

    st.header("품질 관리")

    st.write("제품의 품질과 불량률을 확인하는 화면입니다.")

    st.info("추후 설비별 불량률과 품질 경고 기능을 추가합니다.")

# --------------------------------------------------
# 6. 설비 모니터링 메뉴
# --------------------------------------------------

elif menu == "설비 모니터링":

    st.header("설비 모니터링")

    st.write("설비별 온도와 습도를 확인하는 화면입니다.")

    st.info("추후 설비 선택과 온도 경고 기능을 추가합니다.")

# --------------------------------------------------
# 7. 데이터 관리 메뉴
# --------------------------------------------------

elif menu == "데이터 관리":

    st.header("데이터 관리")

    st.write("생산 데이터를 조회하고 관리하는 화면입니다.")

    st.info("추후 데이터 검색과 입력 기능을 추가합니다.")
